/* 就近匹配城市名（等距圆柱近似）；超过约 300km 无城市覆盖时返回 null（境外/远海） */
export function nearestCity(lng: number, lat: number): string | null {
  let best: string | null = null
  let bestD = Infinity
  const cosLat = Math.cos((lat * Math.PI) / 180)
  for (const [name, cLng, cLat] of CHINA_CITIES) {
    const dx = (lng - cLng) * cosLat
    const dy = lat - cLat
    const d = dx * dx + dy * dy
    if (d < bestD) { bestD = d; best = name }
  }
  return bestD <= 2.7 * 2.7 ? best : null
}
